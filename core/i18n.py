_current_language = "en"
_listeners: set[Callable[[], None]] = set()


def get_language() -> str:
    return _current_language


def set_language(language: str):
    global _current_language
    if language not in _TRANSLATIONS:
        language = "en"
    if _current_language == language:
        return
    _current_language = language
    for listener in list(_listeners):
        try:
            listener()
        except Exception:
            pass


def on_language_changed(listener: Callable[[], None]):
    _listeners.add(listener)


def remove_language_listener(listener: Callable[[], None]):
    _listeners.discard(listener)


def tr(key: str, **kwargs) -> str:
    lang_map = _TRANSLATIONS.get(_current_language, _TRANSLATIONS["en"])
    text = lang_map.get(key, _TRANSLATIONS["en"].get(key, key))
    return text.format(**kwargs) if kwargs else text
